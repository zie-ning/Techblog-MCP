def evidence_retry(failed: list[str]) -> str:
    listed = "\n".join(f"- {e}" for e in failed)
    return f"""\
방금 결과의 다음 evidence는 원문에서 찾을 수 없었다.
{listed}

같은 글을 다시 구조화하라. 이번에는 모든 evidence를 원문에서 글자 그대로 복사하고,
서로 떨어진 문장을 이어 붙이지 마라. 원문에서 근거를 찾을 수 없는 항목은 아예 빼라."""
